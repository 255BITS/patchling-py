"""
Module: applydiff

Contains the function to apply unified git diffs to files on disk.
"""

from pathlib import Path
import re
import hashlib
from collections import defaultdict

# Same separators as extractDiffBlocks in 255BITS/patchling (src/text.js).
# str.splitlines() also splits on vertical tab and unicode separators, which
# would diverge from that reference.
_LINE_BREAK = re.compile(r"\r\n|\r|\n")


def extract_diff_blocks(text):
    """Extract the bodies of all ```diff fenced code blocks from text.

    Mirrors extractDiffBlocks in the JS sibling repo (255BITS/patchling,
    src/text.js):

    - Only a fence whose language is exactly ``diff`` opens a block. ``diffx``,
      ``python``, and a bare fence are ignored.
    - Prose outside those fences is ignored, and every matching block is
      returned in document order.
    - The captured body keeps the newline that precedes the closing fence.
    - An unterminated block is force-closed so a trailing fence is optional.
    """
    if not text:
        return []

    blocks = []
    in_block = False
    current = []

    def flush():
        # Mirror the JS Markdown tool parser: keep the newline that precedes
        # the closing fence. An empty block is an empty string, not a newline.
        blocks.append("\n".join(current) + "\n" if current else "")

    for line in _LINE_BREAK.split(text):
        stripped = line.strip()
        if not in_block:
            if stripped.startswith("```") and stripped[3:].strip() == "diff":
                in_block = True
                current = []
            continue
        if stripped.startswith("```"):
            flush()
            in_block = False
            current = []
            continue
        current.append(line)

    if in_block:
        flush()
    return blocks


def _prefer_fenced_diff_blocks(diff_text):
    """Use ```diff fence bodies when present; otherwise keep the raw diff.

    Multiple fences are joined the same way the JS callLlmForDiff path joins
    extractDiffBlocks() results, with a newline between blocks. Each block
    already ends in a newline, so adjacent blocks stay separated by a blank
    line and remain valid unified diffs.
    """
    blocks = extract_diff_blocks(diff_text)
    if not blocks:
        return diff_text
    return "\n".join(blocks)


def apply_diff(project_dir, diff_text):
    """
    Applies a unified diff (as generated by git diff) to the files in project_dir
    using pure Python (without calling the external 'patch' command).

    Handles file modifications, new file creation, and file deletions.

    Returns:
        True if at least one file was modified (or deleted/created) as a result of the patch,
        False otherwise.
    """
    from pathlib import Path
    import re, hashlib

    def file_hash(filepath):
        h = hashlib.sha256()
        with open(filepath, "rb") as f:
            h.update(f.read())
        return h.hexdigest()

    def apply_patch_to_file(file_path, patch):
        """
        Applies a unified diff patch (for a single file) to file_path.

        Returns True if the patch was applied successfully, False otherwise.
        """
        # Read the original file lines; if the file doesn't exist, treat it as empty.
        if file_path.exists():
            original_lines = file_path.read_text(encoding="utf8").splitlines(keepends=True)
        else:
            original_lines = []
        new_lines = []
        current_index = 0

        patch_lines = patch.splitlines()
        # Regex for a hunk header, e.g., @@ -3,7 +3,6 @@
        hunk_header_re = re.compile(r"^@@(?: -(\d+)(?:,(\d+))?)?(?: \+(\d+)(?:,(\d+))?)? @@")
        i = 0
        while i < len(patch_lines):
            line = patch_lines[i]
            if line.lstrip().startswith("@@"):
                if line.strip() == "@@":
                    # Handle minimal hunk header without line numbers.
                    orig_start = 1
                else:
                    m = hunk_header_re.match(line.strip())
                    if not m:
                        print("Invalid hunk header:", line)
                        return False
                    orig_start = int(m.group(1)) if m.group(1) is not None else 1
                hunk_start_index = orig_start - 1  # diff headers are 1-indexed
                if hunk_start_index > len(original_lines):
                    print("Hunk start index beyond file length")
                    return False
                new_lines.extend(original_lines[current_index:hunk_start_index])
                current_index = hunk_start_index
                i += 1
                # Process the hunk lines until the next hunk header.
                while i < len(patch_lines) and not patch_lines[i].startswith("@@"):
                    pline = patch_lines[i]
                    if pline.startswith(" "):
                        # Context line must match exactly.
                        expected = pline[1:]
                        if current_index >= len(original_lines):
                            print("Context line expected but file ended")
                            return False
                        orig_line = original_lines[current_index].rstrip("\n")
                        if orig_line != expected:
                            print("Context line mismatch. Expected:", expected, "Got:", orig_line)
                            return False
                        new_lines.append(original_lines[current_index])
                        current_index += 1
                    elif pline.startswith("-"):
                        # Removal line: verify and skip from original.
                        expected = pline[1:]
                        if current_index >= len(original_lines):
                            print("Removal line expected but file ended")
                            return False
                        orig_line = original_lines[current_index].rstrip("\n")
                        if orig_line != expected:
                            print("Removal line mismatch. Expected:", expected, "Got:", orig_line)
                            return False
                        current_index += 1
                    elif pline.startswith("+"):
                        # Addition line: add to new_lines.
                        new_lines.append(pline[1:] + "\n")
                    else:
                        try:
                            expected = pline
                            if current_index >= len(original_lines):
                                print("We are trying a smart diff, dumb diff failed")
                                return False
                            orig_line = original_lines[current_index].rstrip("\n")
                            if orig_line != expected:
                                print("We are trying a smart diff, dumb diff failed")
                                return False
                            new_lines.append(original_lines[current_index])
                            current_index += 1
                        except Exception as e:
                            print("We are trying a smart diff, dumb diff failed")
                            print("Exception while applying dumb diff:", e)
                            return False

                    i += 1
            else:
                # Skip non-hunk header lines.
                i += 1

        # Append any remaining lines from the original file.
        new_lines.extend(original_lines[current_index:])
        # Ensure parent directories exist before writing the file.
        file_path.parent.mkdir(parents=True, exist_ok=True)
        # Write the new content back to the file. Ensure the file ends with a newline
        # to match typical patch behavior and avoid tooling conflicts.
        content = "".join(new_lines)
        if content and not content.endswith("\n"):
            content += "\n"
        file_path.write_text(content, encoding="utf8")
        return True

    # Parse the diff into per-file patches.
    file_patches = parse_diff_per_file(diff_text)
    if not file_patches:
        print("No file patches found in diff.")
        return False

    # Record original file hashes.
    original_hashes = {}
    for file_path, _ in file_patches:
        target_file = Path(project_dir) / file_path
        if target_file.exists():
            original_hashes[file_path] = file_hash(target_file)
        else:
            original_hashes[file_path] = None

    any_change = False
    # Process each file patch.
    for file_path, patch in file_patches:
        target_file = Path(project_dir) / file_path
        if "+++ /dev/null" in patch:
            # Deletion patch: delete the file if it exists.
            if target_file.exists():
                target_file.unlink()
                if not target_file.exists():
                    any_change = True
                else:
                    print(f"Failed to delete file: {target_file}")
                    return False
        else:
            # Modification or new file creation.
            success = apply_patch_to_file(target_file, patch)
            if not success:
                print(f"Failed to apply patch to file: {target_file}")
                return False

    # Verify that at least one file was changed by comparing hashes.
    for file_path, patch in file_patches:
        target_file = Path(project_dir) / file_path
        if "+++ /dev/null" in patch:
            if not target_file.exists():
                any_change = True
            else:
                print(f"Expected deletion but file still exists: {target_file}")
                return False
        else:
            old_hash = original_hashes.get(file_path)
            if target_file.exists():
                new_hash = file_hash(target_file)
                if old_hash != new_hash:
                    any_change = True
                else:
                    print(f"No change detected in file: {target_file}")
            else:
                print(f"Expected modification or creation but file is missing: {target_file}")
                return False

    if not any_change:
        print("Patch applied but no file modifications detected.")
        return False
    return True

def parse_diff_per_file(diff_text):
    """Parse unified diff text into individual file patches.

    Splits a multi-file diff into per-file entries for processing. Handles:
    - File creations (+++ /dev/null)
    - File deletions (--- /dev/null)
    - Standard modifications

    Args:
        diff_text: Unified diff string as generated by `git diff`

    Returns:
        List of tuples (file_path, patch) where:
        - file_path: Relative path to modified file
        - patch: Full diff fragment for this file

    Note:
        Uses 'b/' prefix detection from git diffs to determine target paths
        This doesn't work all the time and needs to be revised with stronger models

    Diffs wrapped in one or more ```diff code fences are extracted first,
    including when those fences are surrounded by prose. Text with no ```diff
    fence is parsed unchanged.
    """
    diff_text = _prefer_fenced_diff_blocks(diff_text)

    def dedup_diffs(diffs):
        groups = defaultdict(list)
        for key, value in diffs:
            groups[key].append(value)
        return [[key, "\n".join(values)] for key, values in groups.items()]

    # Special case: handle LLM-style patch delimiters
    if "*** Begin Patch" in diff_text:
        lines = diff_text.splitlines()
        diffs = []
        current_lines = []
        current_file = None
        in_patch = False
        for line in lines:
            stripped = line.strip()
            if stripped == "*** Begin Patch":
                in_patch = True
                current_lines = []
                current_file = None
            elif stripped == "*** End Patch":
                if current_file is not None:
                    diffs.append((current_file, "\n".join(current_lines)))
                in_patch = False
            elif in_patch:
                if stripped.startswith("*** Update File:"):
                    current_file = stripped.split(":", 1)[1].strip()
                else:
                    current_lines.append(line)
        return dedup_diffs(diffs)

    header_re = re.compile(r'^(?:diff --git\s+)?(a/[^ ]+)\s+(b/[^ ]+)\s*$', re.MULTILINE)
    lines = diff_text.splitlines()

    # Check if any header line exists.
    if not any(header_re.match(line) for line in lines):
        # Fallback strategy: detect file headers starting with '---' / '+++' pairs
        diffs = []
        current_lines = []
        current_file = None
        deletion_mode = False
        from_header = None
        header_from_re = re.compile(r'^-{2,3}\s+(.*)$')
        header_to_re = re.compile(r'^\+{2,3}\s+(.*)$')

        for line in lines:
            from_match = header_from_re.match(line)
            to_match = header_to_re.match(line)

            if from_match:
                if current_file is not None and current_lines:
                    if deletion_mode and not any(l.startswith("+++ /dev/null") for l in current_lines):
                        current_lines.append("+++ /dev/null")
                    diffs.append((current_file, "\n".join(current_lines)))
                current_lines = [line]
                deletion_mode = False
                current_file = None
                from_header = from_match.group(1).strip()
                continue

            if to_match and current_lines:
                current_lines.append(line)
                file_to = to_match.group(1).strip()

                if file_to == "/dev/null":
                    deletion_mode = True
                    if from_header and from_header != "/dev/null":
                        current_file = from_header[2:] if (from_header.startswith("a/") or from_header.startswith("b/")) else from_header
                else:
                    current_file = file_to[2:] if (file_to.startswith("a/") or file_to.startswith("b/")) else file_to
                continue

            current_lines.append(line)
            if "deleted file mode" in line:
                deletion_mode = True

        if current_file is not None and current_lines:
            if deletion_mode and not any(l.startswith("+++ ") for l in current_lines):
                current_lines.append("+++ /dev/null")
            diffs.append((current_file, "\n".join(current_lines)))
        return dedup_diffs(diffs)
    else:
        # Use header-based strategy.
        diffs = []
        current_lines = []
        current_file = None
        deletion_mode = False
        for line in lines:
            m = header_re.match(line)
            if m:
                if current_file is not None and current_lines:
                    if deletion_mode and not any(l.startswith("+++ ") for l in current_lines):
                        current_lines.append("+++ /dev/null")
                    diffs.append((current_file, "\n".join(current_lines)))
                current_lines = [line]
                deletion_mode = False
                file_from = m.group(1)  # e.g. "a/index.html"
                file_to = m.group(2)    # e.g. "b/index.html"
                current_file = file_to[2:] if file_to.startswith("b/") else file_to
            else:
                current_lines.append(line)
                if "deleted file mode" in line:
                    deletion_mode = True
                if line.startswith("+++ "):
                    parts = line.split()
                    if len(parts) >= 2:
                        file_to = parts[1].strip()
                        if file_to != "/dev/null":
                            current_file = file_to[2:] if (file_to.startswith("a/") or file_to.startswith("b/")) else file_to
        if current_file is not None and current_lines:
            if deletion_mode and not any(l.startswith("+++ ") for l in current_lines):
                current_lines.append("+++ /dev/null")
            diffs.append((current_file, "\n".join(current_lines)))
        return dedup_diffs(diffs)


# ---------------------------------------------------------------------------
# In-memory appliers used by smartapply before (and as a check on) the LLM.
# ---------------------------------------------------------------------------

_HUNK_HEADER_RE = re.compile(
    r"^@@(?: -(\d+)(?:,(\d+))?)?(?: \+(\d+)(?:,(\d+))?)? @@"
)
_AMBIGUOUS = object()


def _is_ellipsis(text):
    """True for unified-diff 'skip some lines' markers, not literal file text."""
    return text.strip() in {"...", "…", "....", ".."}


def _body_op(pline):
    """Classify one hunk body line.

    Returns ('skip', None), ('ambiguous', None), or (kind, text) where kind
    is 'add', 'del', or 'context'.
    """
    if pline.startswith("\\"):
        # "\ No newline at end of file" — not a content line.
        return ("skip", None)
    if pline.lstrip().startswith("```"):
        # A closing fence left on an LLM diff. Not part of the file.
        return ("skip", None)
    # "++foo" is ambiguous: a doubled addition marker, or a real line that
    # starts with '+'. Either reading can corrupt the file, so refuse.
    if pline.startswith("++") and not pline.startswith("+++"):
        return ("ambiguous", None)
    if pline.startswith("+"):
        return ("add", pline[1:])
    if pline.startswith("-"):
        return ("del", pline[1:])
    if pline.startswith(" "):
        return ("context", pline[1:])
    return ("context", pline)


def _parse_hunks(patch, strict_headers):
    """Parse hunks from a single-file patch.

    Returns a list of (hint, ops), None when the patch cannot be applied by
    this parser, or `_AMBIGUOUS` for a doubled '+' line. Callers must not
    guess at ambiguous lines.
    """
    lines = patch.splitlines()
    hunks = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.lstrip().startswith("@@"):
            i += 1
            continue
        header = line.strip()
        if header == "@@":
            hint = 0
        else:
            match = _HUNK_HEADER_RE.match(header)
            if match:
                orig = int(match.group(1)) if match.group(1) else 1
                hint = max(orig - 1, 0)
            elif strict_headers:
                return None
            else:
                # "@@ ... @@" and other sloppy headers: ignore the numbers.
                hint = 0
        ops = []
        i += 1
        while i < len(lines) and not lines[i].lstrip().startswith("@@"):
            kind, text = _body_op(lines[i])
            i += 1
            if kind == "skip":
                continue
            if kind == "ambiguous":
                return _AMBIGUOUS
            ops.append((kind, text))
        if ops:
            hunks.append((hint, ops))
    if not hunks:
        return None
    return hunks


def _assemble(original, lines):
    """Join patched lines, preserving the original's trailing newline.

    An empty original (a new file) is left without a forced extra newline so
    a pure-addition hunk round-trips to the added text.
    """
    content = "\n".join(lines)
    if content and original.endswith("\n"):
        content += "\n"
    return content


def _find_block(lines, block, min_pos, hint):
    """Index of `block` in `lines` at or after min_pos, nearest to hint."""
    if not block:
        return min(max(hint, min_pos), len(lines))
    best = None
    last = len(lines) - len(block)
    for pos in range(min_pos, last + 1):
        if lines[pos:pos + len(block)] == block:
            if best is None or abs(pos - hint) < abs(best - hint):
                best = pos
    return best


def apply_patch_to_content(original_content, patch):
    """Apply one file's unified diff to a string. None if it does not fit.

    Hunks are located by matching context and deletion lines, not by trusting
    `@@` line numbers (LLM diffs often get those wrong). The `@@` start is
    only a hint when the same block occurs more than once. Context must match
    exactly, so a wrong-context hunk returns None instead of rewriting the
    file with the diff's context text.
    """
    if original_content is None:
        original_content = ""
    parsed = _parse_hunks(patch, strict_headers=True)
    if not parsed or parsed is _AMBIGUOUS:
        return None

    lines = original_content.splitlines()
    new_lines = []
    cursor = 0
    for hint, ops in parsed:
        block = [text for kind, text in ops if kind != "add"]
        pos = _find_block(lines, block, cursor, hint)
        if pos is None:
            return None
        new_lines.extend(lines[cursor:pos])
        idx = pos
        for kind, text in ops:
            if kind == "add":
                new_lines.append(text)
                continue
            if idx >= len(lines) or lines[idx] != text:
                return None
            if kind == "context":
                new_lines.append(lines[idx])
            idx += 1
        cursor = idx
    new_lines.extend(lines[cursor:])
    return _assemble(original_content, new_lines)


_MAX_DEL_CANDIDATES = 32


def _del_assignments(lines, del_texts, min_pos):
    """Increasing index tuples locating each deletion line, or None if too many."""
    found = []

    def rec(di, start, acc):
        if len(found) > _MAX_DEL_CANDIDATES:
            return
        if di == len(del_texts):
            found.append(tuple(acc))
            return
        text = del_texts[di]
        for j in range(start, len(lines)):
            if lines[j] == text:
                acc.append(j)
                rec(di + 1, j + 1, acc)
                acc.pop()
                if len(found) > _MAX_DEL_CANDIDATES:
                    return

    rec(0, min_pos, [])
    if not found or len(found) > _MAX_DEL_CANDIDATES:
        return None
    return found


def _score_assignment(lines, ops, assignment, min_pos):
    """Prefer the deletion site whose real context lines also match.

    Ellipsis markers and context that is simply wrong do not add or subtract.
    They must not be written into the file; they only fail to confirm a site.
    """
    score = 0
    pos = min_pos
    di = 0
    del_indexes = list(assignment)
    for kind, text in ops:
        if kind == "del":
            pos = del_indexes[di] + 1
            di += 1
            score += 1
            continue
        if kind != "context" or _is_ellipsis(text):
            continue
        bound = del_indexes[di] if di < len(del_indexes) else len(lines)
        for j in range(pos, bound):
            if lines[j] == text:
                score += 5
                pos = j + 1
                break
    return score


def _replacement_for_assignment(lines, ops, assignment):
    """File span covering the deletion lines, with only +/- lines changed."""
    span_start = assignment[0]
    span_end = assignment[-1] + 1
    out = []
    pos = span_start
    di = 0
    for kind, text in ops:
        if kind == "add":
            out.append(text)
            continue
        if kind != "del":
            # Context, including mismatched context and ellipsis, is not
            # copied from the diff. Non-deleted file lines stay as they are.
            continue
        idx = assignment[di]
        di += 1
        if idx < pos or idx >= span_end:
            return None
        out.extend(lines[pos:idx])
        pos = idx + 1
    out.extend(lines[pos:span_end])
    return span_start, span_end, out


def _locate_hunk(lines, ops, min_pos):
    del_texts = [text for kind, text in ops if kind == "del"]
    if not del_texts:
        return None
    assignments = _del_assignments(lines, del_texts, min_pos)
    if not assignments:
        return None
    scored = [
        (_score_assignment(lines, ops, assignment, min_pos), assignment)
        for assignment in assignments
    ]
    best = max(score for score, _ in scored)
    winners = [assignment for score, assignment in scored if score == best]
    if len(set(winners)) != 1:
        return None
    return _replacement_for_assignment(lines, ops, winners[0])


def apply_changes_only(original_content, patch):
    """Apply only the diff's '+' and '-' lines. None if that is not safe.

    Wrong-context hunks (bad `@@` numbers, `...` gaps, context text that
    does not match the file) still have a definite edit when each removed
    line occurs in the file. Context text is used only to pick which
    occurrence, and is never written over the file. Unrelated lines, including
    each file's existing first line, stay byte-for-byte.
    """
    if original_content is None:
        original_content = ""
    parsed = _parse_hunks(patch, strict_headers=False)
    if not parsed or parsed is _AMBIGUOUS:
        return None

    lines = original_content.splitlines()
    pieces = []
    cursor = 0
    for _hint, ops in parsed:
        located = _locate_hunk(lines, ops, cursor)
        if located is None:
            return None
        start, end, replacement = located
        if start < cursor:
            return None
        pieces.extend(lines[cursor:start])
        pieces.extend(replacement)
        cursor = end
    pieces.extend(lines[cursor:])
    return _assemble(original_content, pieces)


def _change_spec(patch):
    """Return (deletions, additions, context lines), None, or `_AMBIGUOUS`."""
    parsed = _parse_hunks(patch, strict_headers=False)
    if parsed is None or parsed is _AMBIGUOUS:
        return parsed
    dels = []
    adds = []
    contexts = []
    for _hint, ops in parsed:
        for kind, text in ops:
            if kind == "del":
                dels.append(text)
            elif kind == "add":
                adds.append(text)
            elif not _is_ellipsis(text):
                contexts.append(text)
    return dels, adds, contexts


def _can_consume_all(lines, needed):
    if not needed:
        return True
    have = defaultdict(int)
    for line in lines:
        have[line] += 1
    need = defaultdict(int)
    for line in needed:
        need[line] += 1
    return all(have[text] >= count for text, count in need.items())


def _consume_dels(lines, dels):
    need = defaultdict(int)
    for line in dels:
        need[line] += 1
    remaining = []
    for line in lines:
        if need[line] > 0:
            need[line] -= 1
        else:
            remaining.append(line)
    return remaining


def llm_output_respects_diff(original, updated, patch):
    """True when an LLM rewrite did not leak context or drop unrelated lines.

    Malformed patches (`++` lines, unparseable hunks) return True so the LLM
    can still repair them. When every '-' line is present in the file, the
    rewrite may only remove those lines and add the '+' lines: every other
    original line must survive, in order. Context text that is not already in
    the file must not show up in the result unless it is itself a '+' line.
    """
    if original is None:
        original = ""
    if updated is None:
        return False
    spec = _change_spec(patch)
    if spec is None or spec is _AMBIGUOUS:
        return True
    dels, adds, contexts = spec
    old = original.splitlines()
    new = updated.splitlines()
    add_set = set(adds)
    old_set = set(old)
    for context in contexts:
        if context not in old_set and context in new and context not in add_set:
            return False
    if not _can_consume_all(old, dels):
        # The removed text is not in the file verbatim; the model is doing a
        # fuzzy edit. The context-leak check above is the guard we can apply
        # without rejecting a legitimate fuzzy rewrite.
        return True

    need = defaultdict(int)
    for line in adds:
        need[line] += 1
    remaining = _consume_dels(old, dels)
    ri = 0
    for line in new:
        if ri < len(remaining) and remaining[ri] == line:
            ri += 1
        elif need[line] > 0:
            need[line] -= 1
        else:
            return False
    return ri == len(remaining)


