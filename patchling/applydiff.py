"""
Module: applydiff

Contains the function to apply unified git diffs to files on disk.
"""

from __future__ import annotations

from pathlib import Path
import difflib
import re
import hashlib
from collections import defaultdict

# Same separators as extractDiffBlocks in 255BITS/patchling (src/text.js).
# str.splitlines() also splits on vertical tab and unicode separators, which
# would diverge from that reference.
_LINE_BREAK = re.compile(r"\r\n|\r|\n")


def extract_diff_blocks(text: str | None) -> list[str]:
    """Extract the bodies of all ```diff fenced code blocks from text.

    Mirrors extractDiffBlocks in the JS sibling repo (255BITS/patchling,
    src/text.js):

    - Only a fence whose language is exactly ``diff`` opens a block. ``diffx``,
      ``python``, and a bare fence are ignored.
    - Prose outside those fences is ignored, and every matching block is
      returned in document order.
    - The captured body keeps the newline that precedes the closing fence.
    - An unterminated block is force-closed so a trailing fence is optional.
    """
    if not text:
        return []

    blocks = []
    in_block = False
    current = []

    def flush():
        # Mirror the JS Markdown tool parser: keep the newline that precedes
        # the closing fence. An empty block is an empty string, not a newline.
        blocks.append("\n".join(current) + "\n" if current else "")

    for line in _LINE_BREAK.split(text):
        stripped = line.strip()
        if not in_block:
            if stripped.startswith("```") and stripped[3:].strip() == "diff":
                in_block = True
                current = []
            continue
        if stripped.startswith("```"):
            flush()
            in_block = False
            current = []
            continue
        current.append(line)

    if in_block:
        flush()
    return blocks


def _prefer_fenced_diff_blocks(diff_text):
    """Use ```diff fence bodies when present; otherwise keep the raw diff.

    Multiple fences are joined the same way the JS callLlmForDiff path joins
    extractDiffBlocks() results, with a newline between blocks. Each block
    already ends in a newline, so adjacent blocks stay separated by a blank
    line and remain valid unified diffs.
    """
    blocks = extract_diff_blocks(diff_text)
    if not blocks:
        return diff_text
    return "\n".join(blocks)


class UnsafePathError(ValueError):
    """Raised when a diff/file path would resolve outside the project root."""


def resolve_within(root: str | Path, rel_path: str | Path) -> Path:
    """Join ``rel_path`` onto ``root`` and guarantee the result stays inside it.

    Rejects absolute paths, ``..`` escapes, and symlinks that resolve outside
    ``root``. Returns the joined (unresolved) path on success.
    """
    rel = str(rel_path)
    if not rel or "\x00" in rel:
        raise UnsafePathError(f"Refusing empty/invalid path: {rel!r}")
    candidate = Path(rel)
    if candidate.is_absolute() or rel.startswith(("/", "\\")) or re.match(r"^[A-Za-z]:", rel):
        raise UnsafePathError(f"Refusing absolute path: {rel!r}")
    root_resolved = Path(root).resolve()
    joined = Path(root) / candidate
    resolved = joined.resolve()
    if resolved != root_resolved and root_resolved not in resolved.parents:
        raise UnsafePathError(f"Refusing path outside project root: {rel!r}")
    return joined


def apply_diff(project_dir: str | Path, diff_text: str) -> bool:
    """
    Applies a unified diff (as generated by git diff) to the files in project_dir
    using pure Python (without calling the external 'patch' command).

    Handles file modifications, new file creation, and file deletions.

    Returns:
        True if at least one file was modified (or deleted/created) as a result of the patch,
        False otherwise.
    """
    from pathlib import Path
    import re, hashlib

    def file_hash(filepath):
        h = hashlib.sha256()
        with open(filepath, "rb") as f:
            h.update(f.read())
        return h.hexdigest()

    def apply_patch_to_file(file_path, patch):
        """
        Applies a unified diff patch (for a single file) to file_path.

        Returns True if the patch was applied successfully, False otherwise.
        """
        # Read the original file lines; if the file doesn't exist, treat it as empty.
        if file_path.exists():
            original_lines = file_path.read_text(encoding="utf8").splitlines(keepends=True)
        else:
            original_lines = []
        new_lines = []
        current_index = 0

        patch_lines = patch.splitlines()
        # Regex for a hunk header, e.g., @@ -3,7 +3,6 @@
        hunk_header_re = re.compile(r"^@@(?: -(\d+)(?:,(\d+))?)?(?: \+(\d+)(?:,(\d+))?)? @@")
        i = 0
        while i < len(patch_lines):
            line = patch_lines[i]
            if line.lstrip().startswith("@@"):
                if line.strip() == "@@":
                    # Handle minimal hunk header without line numbers.
                    orig_start = 1
                else:
                    m = hunk_header_re.match(line.strip())
                    if not m:
                        print("Invalid hunk header:", line)
                        return False
                    orig_start = int(m.group(1)) if m.group(1) is not None else 1
                hunk_start_index = orig_start - 1  # diff headers are 1-indexed
                if hunk_start_index > len(original_lines):
                    print("Hunk start index beyond file length")
                    return False
                new_lines.extend(original_lines[current_index:hunk_start_index])
                current_index = hunk_start_index
                i += 1
                # Process the hunk lines until the next hunk header.
                while i < len(patch_lines) and not patch_lines[i].startswith("@@"):
                    pline = patch_lines[i]
                    if pline.startswith(" "):
                        # Context line must match exactly.
                        expected = pline[1:]
                        if current_index >= len(original_lines):
                            print("Context line expected but file ended")
                            return False
                        orig_line = original_lines[current_index].rstrip("\n")
                        if orig_line != expected:
                            print("Context line mismatch. Expected:", expected, "Got:", orig_line)
                            return False
                        new_lines.append(original_lines[current_index])
                        current_index += 1
                    elif pline.startswith("-"):
                        # Removal line: verify and skip from original.
                        expected = pline[1:]
                        if current_index >= len(original_lines):
                            print("Removal line expected but file ended")
                            return False
                        orig_line = original_lines[current_index].rstrip("\n")
                        if orig_line != expected:
                            print("Removal line mismatch. Expected:", expected, "Got:", orig_line)
                            return False
                        current_index += 1
                    elif pline.startswith("+"):
                        # Addition line: add to new_lines.
                        new_lines.append(pline[1:] + "\n")
                    else:
                        try:
                            expected = pline
                            if current_index >= len(original_lines):
                                print("We are trying a smart diff, dumb diff failed")
                                return False
                            orig_line = original_lines[current_index].rstrip("\n")
                            if orig_line != expected:
                                print("We are trying a smart diff, dumb diff failed")
                                return False
                            new_lines.append(original_lines[current_index])
                            current_index += 1
                        except Exception as e:
                            print("We are trying a smart diff, dumb diff failed")
                            print("Exception while applying dumb diff:", e)
                            return False

                    i += 1
            else:
                # Skip non-hunk header lines.
                i += 1

        # Append any remaining lines from the original file.
        new_lines.extend(original_lines[current_index:])
        # Ensure parent directories exist before writing the file.
        file_path.parent.mkdir(parents=True, exist_ok=True)
        # Write the new content back to the file. Ensure the file ends with a newline
        # to match typical patch behavior and avoid tooling conflicts.
        content = "".join(new_lines)
        if content and not content.endswith("\n"):
            content += "\n"
        file_path.write_text(content, encoding="utf8")
        return True

    # Parse the diff into per-file patches.
    file_patches = parse_diff_per_file(diff_text)
    if not file_patches:
        print("No file patches found in diff.")
        return False

    # Reject any path that escapes project_dir before touching the filesystem.
    for file_path, _ in file_patches:
        try:
            resolve_within(project_dir, file_path)
        except UnsafePathError as exc:
            print(str(exc))
            return False

    # Record original file hashes.
    original_hashes = {}
    for file_path, _ in file_patches:
        target_file = Path(project_dir) / file_path
        if target_file.exists():
            original_hashes[file_path] = file_hash(target_file)
        else:
            original_hashes[file_path] = None

    any_change = False
    # Process each file patch.
    for file_path, patch in file_patches:
        target_file = Path(project_dir) / file_path
        if "+++ /dev/null" in patch:
            # Deletion patch: delete the file if it exists.
            if target_file.exists():
                target_file.unlink()
                if not target_file.exists():
                    any_change = True
                else:
                    print(f"Failed to delete file: {target_file}")
                    return False
        else:
            # Modification or new file creation.
            success = apply_patch_to_file(target_file, patch)
            if not success:
                print(f"Failed to apply patch to file: {target_file}")
                return False

    # Verify that at least one file was changed by comparing hashes.
    for file_path, patch in file_patches:
        target_file = Path(project_dir) / file_path
        if "+++ /dev/null" in patch:
            if not target_file.exists():
                any_change = True
            else:
                print(f"Expected deletion but file still exists: {target_file}")
                return False
        else:
            old_hash = original_hashes.get(file_path)
            if target_file.exists():
                new_hash = file_hash(target_file)
                if old_hash != new_hash:
                    any_change = True
                else:
                    print(f"No change detected in file: {target_file}")
            else:
                print(f"Expected modification or creation but file is missing: {target_file}")
                return False

    if not any_change:
        print("Patch applied but no file modifications detected.")
        return False
    return True

def parse_diff_per_file(diff_text: str) -> list[tuple[str, str]]:
    """Parse unified diff text into individual file patches.

    Splits a multi-file diff into per-file entries for processing. Handles:
    - File creations (+++ /dev/null)
    - File deletions (--- /dev/null)
    - Standard modifications

    Args:
        diff_text: Unified diff string as generated by `git diff`

    Returns:
        List of tuples (file_path, patch) where:
        - file_path: Relative path to modified file
        - patch: Full diff fragment for this file

    Note:
        Uses 'b/' prefix detection from git diffs to determine target paths
        This doesn't work all the time and needs to be revised with stronger models

    Diffs wrapped in one or more ```diff code fences are extracted first,
    including when those fences are surrounded by prose. Text with no ```diff
    fence is parsed unchanged.
    """
    diff_text = _prefer_fenced_diff_blocks(diff_text)

    def dedup_diffs(diffs):
        groups = defaultdict(list)
        for key, value in diffs:
            groups[key].append(value)
        return [(key, "\n".join(values)) for key, values in groups.items()]

    # Special case: handle LLM-style patch delimiters
    if "*** Begin Patch" in diff_text:
        lines = diff_text.splitlines()
        diffs = []
        current_lines = []
        current_file = None
        in_patch = False
        for line in lines:
            stripped = line.strip()
            if stripped == "*** Begin Patch":
                in_patch = True
                current_lines = []
                current_file = None
            elif stripped == "*** End Patch":
                if current_file is not None:
                    diffs.append((current_file, "\n".join(current_lines)))
                in_patch = False
            elif in_patch:
                if stripped.startswith("*** Update File:"):
                    current_file = stripped.split(":", 1)[1].strip()
                else:
                    current_lines.append(line)
        return dedup_diffs(diffs)

    header_re = re.compile(r'^(?:diff --git\s+)?(a/[^ ]+)\s+(b/[^ ]+)\s*$', re.MULTILINE)
    lines = diff_text.splitlines()

    # Check if any header line exists.
    if not any(header_re.match(line) for line in lines):
        # Fallback strategy: detect file headers starting with '---' / '+++' pairs
        diffs = []
        current_lines = []
        current_file = None
        deletion_mode = False
        from_header = None
        header_from_re = re.compile(r'^-{2,3}\s+(.*)$')
        header_to_re = re.compile(r'^\+{2,3}\s+(.*)$')

        for line in lines:
            from_match = header_from_re.match(line)
            to_match = header_to_re.match(line)

            if from_match:
                if current_file is not None and current_lines:
                    if deletion_mode and not any(l.startswith("+++ /dev/null") for l in current_lines):
                        current_lines.append("+++ /dev/null")
                    diffs.append((current_file, "\n".join(current_lines)))
                current_lines = [line]
                deletion_mode = False
                current_file = None
                from_header = from_match.group(1).strip()
                continue

            if to_match and current_lines:
                current_lines.append(line)
                file_to = to_match.group(1).strip()

                if file_to == "/dev/null":
                    deletion_mode = True
                    if from_header and from_header != "/dev/null":
                        current_file = from_header[2:] if (from_header.startswith("a/") or from_header.startswith("b/")) else from_header
                else:
                    current_file = file_to[2:] if (file_to.startswith("a/") or file_to.startswith("b/")) else file_to
                continue

            current_lines.append(line)
            if "deleted file mode" in line:
                deletion_mode = True

        if current_file is not None and current_lines:
            if deletion_mode and not any(l.startswith("+++ ") for l in current_lines):
                current_lines.append("+++ /dev/null")
            diffs.append((current_file, "\n".join(current_lines)))
        return dedup_diffs(diffs)
    else:
        # Use header-based strategy.
        diffs = []
        current_lines = []
        current_file = None
        deletion_mode = False
        for line in lines:
            m = header_re.match(line)
            if m:
                if current_file is not None and current_lines:
                    if deletion_mode and not any(l.startswith("+++ ") for l in current_lines):
                        current_lines.append("+++ /dev/null")
                    diffs.append((current_file, "\n".join(current_lines)))
                current_lines = [line]
                deletion_mode = False
                file_from = m.group(1)  # e.g. "a/index.html"
                file_to = m.group(2)    # e.g. "b/index.html"
                current_file = file_to[2:] if file_to.startswith("b/") else file_to
            else:
                current_lines.append(line)
                if "deleted file mode" in line:
                    deletion_mode = True
                if line.startswith("+++ "):
                    parts = line.split()
                    if len(parts) >= 2:
                        file_to = parts[1].strip()
                        if file_to != "/dev/null":
                            current_file = file_to[2:] if (file_to.startswith("a/") or file_to.startswith("b/")) else file_to
        if current_file is not None and current_lines:
            if deletion_mode and not any(l.startswith("+++ ") for l in current_lines):
                current_lines.append("+++ /dev/null")
            diffs.append((current_file, "\n".join(current_lines)))
        return dedup_diffs(diffs)


# ---------------------------------------------------------------------------
# In-memory appliers used by smartapply before (and as a check on) the LLM.
# ---------------------------------------------------------------------------

_HUNK_HEADER_RE = re.compile(
    r"^@@(?: -(\d+)(?:,(\d+))?)?(?: \+(\d+)(?:,(\d+))?)? @@"
)
_AMBIGUOUS = object()


def _is_ellipsis(text):
    """True for unified-diff 'skip some lines' markers, not literal file text."""
    return text.strip() in {"...", "…", "....", ".."}


# Whole-line similarity at or above this counts as the same context line.
# 0.91 accepts the Express path/await drift in hard_drifted_js (~0.91–0.93)
# and rejects case-only drift such as `False` vs `false` (~0.909) and
# signature rewrites such as `def total(items)` vs `def total(self, items)`.
_CONTEXT_ANCHOR_MIN = 0.91
_IDENT_PAIR_MIN = 0.55
_IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def _trivial_key(line):
    """Identity ignoring whitespace and trailing semicolons.

    `TIMEOUT = 30` and `TIMEOUT=30` are the same line, as are `res.json(user)`
    and `res.json(user);`. The comparison is case-sensitive, so `False` and
    `false` stay different.
    """
    collapsed = re.sub(r"\s+", "", line or "")
    while collapsed.endswith(";"):
        collapsed = collapsed[:-1]
    return collapsed


def _same_trivial(a, b):
    return a == b or _trivial_key(a) == _trivial_key(b)


def _context_anchor_score(diff_line, file_line):
    """How confidently `diff_line` is a trivial drift of `file_line`.

    1.0 means whitespace/semicolons only. Otherwise a sequence ratio, so a
    drifted path or a missing `await` can still count as that context line.
    """
    if _same_trivial(diff_line, file_line):
        return 1.0
    left = _trivial_key(diff_line)
    right = _trivial_key(file_line)
    if len(left) < 4 or len(right) < 4:
        return 0.0
    return difflib.SequenceMatcher(None, left, right).ratio()


def _lines_match(diff_line, file_line):
    """True when a model line is the file line or a trivial drift of it."""
    return (
        _same_trivial(diff_line, file_line)
        or _context_anchor_score(diff_line, file_line) >= _CONTEXT_ANCHOR_MIN
    )


def _apply_ident_map(text, mapping):
    if not mapping:
        return text

    def repl(match):
        return mapping.get(match.group(0), match.group(0))

    return _IDENT_RE.sub(repl, text)


def _ident_map_for_lines(lines, contexts, start=0, end=None):
    """Map drifted diff identifiers onto the names the file actually uses.

    A context line pairs with a file line only when they are the best match
    near the edit and contain the same number of identifiers, so
    `database.get(user_id)` can teach `user_id` → `uid` without rewriting
    unrelated lines. Conflicting mappings are dropped.
    """
    if end is None:
        end = len(lines)
    start = max(0, start)
    end = min(len(lines), end)
    mapping = {}
    conflicts = set()
    for text in contexts:
        if _is_ellipsis(text):
            continue
        best_i = None
        best_s = _IDENT_PAIR_MIN
        for i in range(start, end):
            score = _context_anchor_score(text, lines[i])
            if score > best_s:
                best_s = score
                best_i = i
        if best_i is None:
            continue
        diff_ids = _IDENT_RE.findall(text)
        file_ids = _IDENT_RE.findall(lines[best_i])
        if len(diff_ids) != len(file_ids):
            continue
        for src, dst in zip(diff_ids, file_ids):
            if src == dst:
                continue
            prev = mapping.get(src)
            if prev is None:
                mapping[src] = dst
            elif prev != dst:
                conflicts.add(src)
    for src in conflicts:
        mapping.pop(src, None)
    return mapping


def _body_op(pline):
    """Classify one hunk body line.

    Returns ('skip', None), ('ambiguous', None), or (kind, text) where kind
    is 'add', 'del', or 'context'.
    """
    if pline.startswith("\\"):
        # "\ No newline at end of file" — not a content line.
        return ("skip", None)
    if pline.lstrip().startswith("```"):
        # A closing fence left on an LLM diff. Not part of the file.
        return ("skip", None)
    # "++foo" is ambiguous: a doubled addition marker, or a real line that
    # starts with '+'. Either reading can corrupt the file, so refuse.
    if pline.startswith("++") and not pline.startswith("+++"):
        return ("ambiguous", None)
    if pline.startswith("+"):
        return ("add", pline[1:])
    if pline.startswith("-"):
        return ("del", pline[1:])
    if pline.startswith(" "):
        return ("context", pline[1:])
    return ("context", pline)


def _parse_hunks(patch, strict_headers):
    """Parse hunks from a single-file patch.

    Returns a list of (hint, ops), None when the patch cannot be applied by
    this parser, or `_AMBIGUOUS` for a doubled '+' line. Callers must not
    guess at ambiguous lines.
    """
    lines = patch.splitlines()
    hunks = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.lstrip().startswith("@@"):
            i += 1
            continue
        header = line.strip()
        if header == "@@":
            hint = 0
        else:
            match = _HUNK_HEADER_RE.match(header)
            if match:
                orig = int(match.group(1)) if match.group(1) else 1
                hint = max(orig - 1, 0)
            elif strict_headers:
                return None
            else:
                # "@@ ... @@" and other sloppy headers: ignore the numbers.
                hint = 0
        ops = []
        i += 1
        while i < len(lines) and not lines[i].lstrip().startswith("@@"):
            kind, text = _body_op(lines[i])
            i += 1
            if kind == "skip":
                continue
            if kind == "ambiguous":
                return _AMBIGUOUS
            ops.append((kind, text))
        if ops:
            hunks.append((hint, ops))
    if not hunks:
        return None
    return hunks


def _assemble(original, lines):
    """Join patched lines, preserving the original's trailing newline.

    An empty original (a new file) is left without a forced extra newline so
    a pure-addition hunk round-trips to the added text.
    """
    content = "\n".join(lines)
    if content and original.endswith("\n"):
        content += "\n"
    return content


def _find_block(lines, block, min_pos, hint):
    """Index of `block` in `lines` at or after min_pos, nearest to hint."""
    if not block:
        return min(max(hint, min_pos), len(lines))
    best = None
    last = len(lines) - len(block)
    for pos in range(min_pos, last + 1):
        if lines[pos:pos + len(block)] == block:
            if best is None or abs(pos - hint) < abs(best - hint):
                best = pos
    return best


def apply_patch_to_content(original_content: str | None, patch: str) -> str | None:
    """Apply one file's unified diff to a string. None if it does not fit.

    Hunks are located by matching context and deletion lines, not by trusting
    `@@` line numbers (LLM diffs often get those wrong). The `@@` start is
    only a hint when the same block occurs more than once. Context must match
    exactly, so a wrong-context hunk returns None instead of rewriting the
    file with the diff's context text.
    """
    if original_content is None:
        original_content = ""
    parsed = _parse_hunks(patch, strict_headers=True)
    if not parsed or parsed is _AMBIGUOUS:
        return None

    lines = original_content.splitlines()
    new_lines = []
    cursor = 0
    for hint, ops in parsed:
        block = [text for kind, text in ops if kind != "add"]
        pos = _find_block(lines, block, cursor, hint)
        if pos is None:
            return None
        new_lines.extend(lines[cursor:pos])
        idx = pos
        for kind, text in ops:
            if kind == "add":
                new_lines.append(text)
                continue
            if idx >= len(lines) or lines[idx] != text:
                return None
            if kind == "context":
                new_lines.append(lines[idx])
            idx += 1
        cursor = idx
    new_lines.extend(lines[cursor:])
    return _assemble(original_content, new_lines)


_MAX_DEL_CANDIDATES = 32


def _del_assignments(lines, del_texts, min_pos):
    """Increasing index tuples locating each deletion line, or None if too many."""
    found = []

    def rec(di, start, acc):
        if len(found) > _MAX_DEL_CANDIDATES:
            return
        if di == len(del_texts):
            found.append(tuple(acc))
            return
        text = del_texts[di]
        for j in range(start, len(lines)):
            if _same_trivial(lines[j], text):
                acc.append(j)
                rec(di + 1, j + 1, acc)
                acc.pop()
                if len(found) > _MAX_DEL_CANDIDATES:
                    return

    rec(0, min_pos, [])
    if not found or len(found) > _MAX_DEL_CANDIDATES:
        return None
    return found


def _score_assignment(lines, ops, assignment, min_pos):
    """Prefer the deletion site whose real context lines also match.

    Ellipsis markers and context that is simply wrong do not add or subtract.
    They must not be written into the file; they only fail to confirm a site.
    """
    score = 0
    pos = min_pos
    di = 0
    del_indexes = list(assignment)
    for kind, text in ops:
        if kind == "del":
            pos = del_indexes[di] + 1
            di += 1
            score += 1
            continue
        if kind != "context" or _is_ellipsis(text):
            continue
        bound = del_indexes[di] if di < len(del_indexes) else len(lines)
        for j in range(pos, bound):
            if _same_trivial(lines[j], text):
                score += 5
                pos = j + 1
                break
    return score


def _replacement_for_assignment(lines, ops, assignment):
    """File span covering the deletion lines, with only +/- lines changed.

    '+' lines are adapted when drifted context reveals a rename
    (`user_id` in the diff, `uid` in the file). Context text itself is
    never written over the file.
    """
    contexts = [text for kind, text in ops if kind == "context"]
    window = 40
    mapping = _ident_map_for_lines(
        lines,
        contexts,
        assignment[0] - window,
        assignment[-1] + 1 + window,
    )
    span_start = assignment[0]
    span_end = assignment[-1] + 1
    out = []
    pos = span_start
    di = 0
    for kind, text in ops:
        if kind == "add":
            out.append(_apply_ident_map(text, mapping))
            continue
        if kind != "del":
            # Context, including mismatched context and ellipsis, is not
            # copied from the diff. Non-deleted file lines stay as they are.
            continue
        idx = assignment[di]
        di += 1
        if idx < pos or idx >= span_end:
            return None
        out.extend(lines[pos:idx])
        pos = idx + 1
    out.extend(lines[pos:span_end])
    return span_start, span_end, out


def _locate_hunk(lines, ops, min_pos):
    del_texts = [text for kind, text in ops if kind == "del"]
    if not del_texts:
        return None
    assignments = _del_assignments(lines, del_texts, min_pos)
    if not assignments:
        return None
    scored = [
        (_score_assignment(lines, ops, assignment, min_pos), assignment)
        for assignment in assignments
    ]
    best = max(score for score, _ in scored)
    winners = [assignment for score, assignment in scored if score == best]
    if len(set(winners)) != 1:
        return None
    return _replacement_for_assignment(lines, ops, winners[0])


def _align_context_anchors(lines, contexts, min_pos):
    """Monotonic file indexes for each context line, or None when it does not fit."""
    indexes = []
    pos = min_pos
    for text in contexts:
        if _is_ellipsis(text):
            indexes.append(None)
            continue
        best_i = None
        best_s = _CONTEXT_ANCHOR_MIN
        for i in range(pos, len(lines)):
            score = _context_anchor_score(text, lines[i])
            if score >= _CONTEXT_ANCHOR_MIN and (best_i is None or score > best_s):
                best_s = score
                best_i = i
        indexes.append(best_i)
        if best_i is not None:
            pos = best_i + 1
    return indexes


def _apply_context_anchored_adds(lines, ops, min_pos):
    """Insert '+' lines using drifted context as an anchor. None if unsure.

    Context is not copied from the diff. A whitespace, semicolon, or
    otherwise trivial drift still counts as the file's own line, and the
    additions are placed relative to those lines. At least half of the
    context lines must anchor, so a single shared closer cannot drag the
    edit into the wrong function.
    """
    contexts = [text for kind, text in ops if kind == "context" and not _is_ellipsis(text)]
    if not contexts or not any(kind == "add" for kind, _text in ops):
        return None
    anchors = _align_context_anchors(lines, contexts, min_pos)
    anchor_at = iter(anchors)
    before = defaultdict(list)
    pending = []
    last = None
    matched = 0
    for kind, text in ops:
        if kind == "add":
            pending.append(text)
            continue
        if kind != "context" or _is_ellipsis(text):
            continue
        idx = next(anchor_at)
        if idx is None:
            continue
        matched += 1
        if pending:
            before[idx].extend(pending)
            pending = []
        last = idx
    if pending:
        if last is None:
            return None
        before[last + 1].extend(pending)
    if matched == 0 or matched * 2 < len(contexts) or not before:
        return None
    if min(before) < min_pos:
        return None
    span_start = min(before)
    last_anchor = last if last is not None else span_start
    span_end = max(last_anchor + 1, span_start)
    out = []
    for i in range(span_start, span_end):
        out.extend(before.get(i, []))
        out.append(lines[i])
    out.extend(before.get(span_end, []))
    return span_start, span_end, out


def _locate_edit(lines, ops, min_pos):
    """Locate one hunk. Deletions win; pure additions use drifted context."""
    if any(kind == "del" for kind, _text in ops):
        return _locate_hunk(lines, ops, min_pos)
    if any(kind == "add" for kind, _text in ops):
        return _apply_context_anchored_adds(lines, ops, min_pos)
    return (min_pos, min_pos, [])


def apply_changes_only(original_content: str | None, patch: str) -> str | None:
    """Apply only the diff's '+' and '-' lines. None if that is not safe.

    Wrong-context hunks (bad `@@` numbers, `...` gaps, context text that
    does not match the file) still have a definite edit when each removed
    line occurs in the file. Whitespace-only and trailing-semicolon drift
    still counts as that line. Context text is used only to pick which
    occurrence, and is never written over the file. A pure-addition hunk
    whose context is only trivially drifted is inserted beside the matching
    file lines. Unrelated lines, including each file's existing first line,
    stay byte-for-byte.
    """
    if original_content is None:
        original_content = ""
    parsed = _parse_hunks(patch, strict_headers=False)
    if not parsed or parsed is _AMBIGUOUS:
        return None

    lines = original_content.splitlines()
    pieces = []
    cursor = 0
    for _hint, ops in parsed:
        located = _locate_edit(lines, ops, cursor)
        if located is None:
            return None
        start, end, replacement = located
        if start < cursor:
            return None
        pieces.extend(lines[cursor:start])
        pieces.extend(replacement)
        cursor = end
    pieces.extend(lines[cursor:])
    return _assemble(original_content, pieces)


def _change_spec(patch):
    """Return (deletions, additions, context lines), None, or `_AMBIGUOUS`."""
    parsed = _parse_hunks(patch, strict_headers=False)
    if parsed is None or parsed is _AMBIGUOUS:
        return parsed
    dels = []
    adds = []
    contexts = []
    for _hint, ops in parsed:
        for kind, text in ops:
            if kind == "del":
                dels.append(text)
            elif kind == "add":
                adds.append(text)
            elif not _is_ellipsis(text):
                contexts.append(text)
    return dels, adds, contexts


def _context_is_known(context, old, adds):
    """True when a diff context line is already a file line or a trivial drift of one."""
    if any(_lines_match(context, line) for line in old):
        return True
    return any(_same_trivial(context, line) for line in adds)


def _consume_dels_trivial(lines, dels):
    """Drop deletion lines, allowing whitespace and semicolon drift.

    Returns (remaining, unmatched). `unmatched` is every '-' line that is
    not in the file even after that normalization.
    """
    need = list(dels)
    remaining = []
    for line in lines:
        hit = None
        for i, text in enumerate(need):
            if _same_trivial(line, text):
                hit = i
                break
        if hit is None:
            remaining.append(line)
        else:
            need.pop(hit)
    return remaining, need


def _addition_matches(line, additions, mapped):
    for i, add in enumerate(additions):
        if _same_trivial(line, add) or _same_trivial(line, mapped[i]) or _lines_match(add, line):
            return i
    return None


def llm_output_respects_diff(original: str | None, updated: str | None, patch: str) -> bool:
    """True when an LLM rewrite did not leak context or drop unrelated lines.

    Malformed patches (`++` lines, unparseable hunks) return True so the LLM
    can still repair them. When every '-' line is present in the file, the
    rewrite may only remove those lines and add the '+' lines: every other
    original line must survive, in order. Whitespace, trailing semicolons,
    and trivially drifted context (a changed path or a missing `await` on a
    line the diff already named) count as that context line. A line the diff
    never mentions must still be present. Context text that is not a drift of
    a file line must not show up unless it is itself a '+' line.
    """
    if original is None:
        original = ""
    if updated is None:
        return False
    spec = _change_spec(patch)
    if spec is None or spec is _AMBIGUOUS:
        return True
    dels, adds, contexts = spec
    old = original.splitlines()
    new = updated.splitlines()
    ident_map = _ident_map_for_lines(old, contexts)
    mapped_adds = [_apply_ident_map(add, ident_map) for add in adds]
    for context in contexts:
        if _context_is_known(context, old, adds):
            continue
        mapped = _apply_ident_map(context, ident_map)
        if mapped != context and any(_same_trivial(mapped, line) for line in old):
            continue
        if any(_same_trivial(context, line) for line in new):
            return False
    remaining, unmatched = _consume_dels_trivial(old, dels)
    if unmatched:
        # The removed text is not in the file even after whitespace and
        # semicolon normalization. The model is doing a fuzzy edit (for
        # example a quote change). Don't reject that here; empty and
        # drastically shrunken rewrites are refused separately.
        return True

    add_left = list(adds)
    mapped_left = list(mapped_adds)
    ri = 0
    for line in new:
        if ri < len(remaining) and _lines_match(remaining[ri], line):
            ri += 1
            continue
        hit = _addition_matches(line, add_left, mapped_left)
        if hit is not None:
            add_left.pop(hit)
            mapped_left.pop(hit)
            continue
        return False
    return ri == len(remaining)


def output_collapsed(original: str | None, updated: str | None, patch: str | None) -> bool:
    """True when model output is empty or drastically shorter than the file.

    A diff that deletes the file (`+++ /dev/null`) may remove every line.
    Otherwise an empty rewrite is refused, as is one that keeps less than
    half of the non-whitespace text the diff itself would leave behind.
    """
    if patch and "+++ /dev/null" in patch:
        return False
    original = original or ""
    updated = "" if updated is None else updated
    old_body = re.sub(r"\s+", "", original)
    if not old_body:
        return False
    if not updated.strip():
        return True
    new_body = re.sub(r"\s+", "", updated)
    spec = _change_spec(patch) if patch else None
    expected = len(old_body)
    if spec and spec is not _AMBIGUOUS:
        dels, adds, _contexts = spec
        removed = sum(len(re.sub(r"\s+", "", line)) for line in dels)
        added = sum(len(re.sub(r"\s+", "", line)) for line in adds)
        expected = len(old_body) - removed + added
    if expected <= 0:
        return False
    return len(new_body) * 2 < expected


